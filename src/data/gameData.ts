export function getNPCScheduleForHour(npc: NPC, hour: number): NPCScheduleSlot | undefined {
  if (!npc.schedule || npc.schedule.length === 0) return undefined;
  return npc.schedule.find(slot => {
    if (slot.startHour <= slot.endHour) {
      return hour >= slot.startHour && hour < slot.endHour;
    } else {
      return hour >= slot.startHour || hour < slot.endHour;
    }
  }) || npc.schedule[0];
}

